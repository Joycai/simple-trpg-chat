-- Apply after 2026-10-29-llm-protocol.sql, before deploying the Vendor/Model UI.
-- Each legacy row gets its own vendor: never merge credentials by name/URL.
BEGIN;
-- Serialize legacy configuration writers while copying credentials/routes.
LOCK TABLE ai_providers IN SHARE ROW EXCLUSIVE MODE;
CREATE TABLE IF NOT EXISTS ai_vendors (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name text NOT NULL, platform text NOT NULL,
  api_key_encrypted text NOT NULL, api_key_hint text,
  routes jsonb NOT NULL, legacy_provider_id integer UNIQUE
);
ALTER TABLE ai_providers ADD COLUMN IF NOT EXISTS vendor_id integer REFERENCES ai_vendors(id) ON DELETE RESTRICT;
ALTER TABLE ai_providers ADD COLUMN IF NOT EXISTS protocol_settings jsonb;
INSERT INTO ai_vendors (owner_id, name, platform, api_key_encrypted, api_key_hint, routes, legacy_provider_id)
SELECT owner_id, name, vendor, api_key_encrypted, api_key_hint,
  jsonb_build_array(jsonb_strip_nulls(jsonb_build_object(
    'protocol', COALESCE(protocol_config->>'protocol', 'chat'), 'endpoint', api_endpoint,
    'endpointMode', COALESCE(protocol_config->>'endpointMode', 'base'), 'auth', protocol_config->>'auth'))), id
FROM ai_providers WHERE vendor_id IS NULL
ON CONFLICT (legacy_provider_id) DO NOTHING;
UPDATE ai_providers p SET vendor_id = v.id,
  protocol_settings = jsonb_build_object(COALESCE(p.protocol_config->>'protocol', 'chat'), COALESCE(p.protocol_config, '{"version":1,"protocol":"chat"}'::jsonb))
FROM ai_vendors v WHERE v.legacy_provider_id = p.id AND p.vendor_id IS NULL;
COMMIT;
